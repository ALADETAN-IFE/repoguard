import {
  parsePackageLock,
  parseYarnLock,
  parsePnpmLock,
  parseBunLock,
  parsePoetryLock,
  parsePipfileLock,
  parseCargoLock,
  findLockfileVersion,
} from "../src/pullRequest/lockfileParsers";
import { generateSuggestionForFinding } from "../src/pullRequest/suggestions";
import type { Finding, OctokitClient } from "../src/types/index";

describe("lockfileParsers", () => {
  describe("parsePackageLock", () => {
    it("parses lockfileVersion 3 node_modules format", () => {
      const lockV3 = JSON.stringify({
        name: "test-app",
        lockfileVersion: 3,
        packages: {
          "": {
            name: "test-app",
            devDependencies: {
              "@react-native-community/cli": "latest",
            },
          },
          "node_modules/@react-native-community/cli": {
            version: "18.0.0",
            resolved:
              "https://registry.npmjs.org/@react-native-community/cli/-/cli-18.0.0.tgz",
          },
        },
      });

      expect(parsePackageLock(lockV3, "@react-native-community/cli")).toBe(
        "18.0.0",
      );
    });

    it("parses lockfileVersion 1 & 2 dependencies format", () => {
      const lockV1 = JSON.stringify({
        name: "test-app",
        lockfileVersion: 1,
        dependencies: {
          lodash: {
            version: "4.17.21",
          },
        },
      });

      expect(parsePackageLock(lockV1, "lodash")).toBe("4.17.21");
    });

    it("returns null if package not found in package-lock.json", () => {
      const lockV3 = JSON.stringify({
        packages: {},
      });
      expect(parsePackageLock(lockV3, "non-existent")).toBeNull();
    });
  });

  describe("parseYarnLock", () => {
    it("parses Yarn Classic (v1) format with multi-specifier header", () => {
      const yarnV1 = `
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT.
# yarn lockfile v1

"@react-native-community/cli@*", "@react-native-community/cli@latest":
  version "18.0.0"
  resolved "https://registry.npmjs.org/@react-native-community/cli/-/cli-18.0.0.tgz"
  integrity sha512-DyKptlG78XPFo7tDod+we5a3R+U9qjyhaVFbOPvH4pFNu5Dehewtol/srl44K6Cszq0aEMlAJZ3juk0W4WnOJA==

"lodash@*":
  version "4.17.21"
`;

      expect(parseYarnLock(yarnV1, "@react-native-community/cli")).toBe(
        "18.0.0",
      );
      expect(parseYarnLock(yarnV1, "lodash")).toBe("4.17.21");
    });

    it("parses Yarn Berry (v2/v3/v4) format", () => {
      const yarnBerry = `
__metadata:
  version: 8

"@react-native-community/cli@npm:latest":
  version: 18.0.0
  resolution: "@react-native-community/cli@npm:18.0.0"
`;

      expect(parseYarnLock(yarnBerry, "@react-native-community/cli")).toBe(
        "18.0.0",
      );
    });
  });

  describe("parsePnpmLock & parseBunLock", () => {
    it("parses pnpm-lock.yaml format", () => {
      const pnpmLock = `
lockfileVersion: '6.0'

dependencies:
  lodash:
    specifier: '*'
    version: 4.17.21

packages:
  /@react-native-community/cli@18.0.0:
    resolution: {integrity: sha512-DyKptlG78XPFo7tDod+we5a3R+U9qjyhaVFbOPvH4pFNu5Dehewtol/srl44K6Cszq0aEMlAJZ3juk0W4WnOJA==}
  /lodash@4.17.21:
    resolution: {integrity: sha512-v2kDEe57lecTulaDIuNTPy3Ry4gLGJ6Z1O3vE1krgXZNrsQ+LFTGHVxVjcXPs17LhbZVGedAJv8XZ1tvj5FvSg==}
`;

      expect(parsePnpmLock(pnpmLock, "@react-native-community/cli")).toBe(
        "18.0.0",
      );
      expect(parsePnpmLock(pnpmLock, "lodash")).toBe("4.17.21");
    });

    it("parses bun.lock format", () => {
      const bunLock = JSON.stringify({
        packages: {
          "@react-native-community/cli": "18.0.0",
        },
      });
      expect(parseBunLock(bunLock, "@react-native-community/cli")).toBe(
        "18.0.0",
      );
    });
  });

  describe("parsePoetryLock & parsePipfileLock & parseCargoLock", () => {
    it("parses poetry.lock", () => {
      const poetryLock = `
[[package]]
name = "requests"
version = "2.31.0"
description = "Python HTTP for Humans."
`;
      expect(parsePoetryLock(poetryLock, "requests")).toBe("2.31.0");
    });

    it("parses Pipfile.lock", () => {
      const pipfileLock = JSON.stringify({
        default: {
          requests: {
            version: "==2.31.0",
          },
        },
      });
      expect(parsePipfileLock(pipfileLock, "requests")).toBe("2.31.0");
    });

    it("parses Cargo.lock", () => {
      const cargoLock = `
[[package]]
name = "serde"
version = "1.0.197"
source = "registry+https://github.com/rust-lang/crates.io-index"
`;
      expect(parseCargoLock(cargoLock, "serde")).toBe("1.0.197");
    });
  });

  describe("findLockfileVersion across ALL lockfiles", () => {
    it("resolves version when npm, yarn, and pnpm all agree", async () => {
      const mockOctokit = {
        request: jest
          .fn()
          .mockImplementation((endpoint: string, params: any) => {
            if (params.path === "azapal-mobile/package-lock.json") {
              return Promise.resolve({
                data: {
                  type: "file",
                  content: Buffer.from(
                    JSON.stringify({
                      packages: {
                        "node_modules/@react-native-community/cli": {
                          version: "18.0.0",
                        },
                      },
                    }),
                  ).toString("base64"),
                },
              });
            }
            if (params.path === "azapal-mobile/yarn.lock") {
              return Promise.resolve({
                data: {
                  type: "file",
                  content: Buffer.from(
                    '"@react-native-community/cli@latest":\n  version "18.0.0"\n',
                  ).toString("base64"),
                },
              });
            }
            if (params.path === "azapal-mobile/pnpm-lock.yaml") {
              return Promise.resolve({
                data: {
                  type: "file",
                  content: Buffer.from(
                    "packages:\n  /@react-native-community/cli@18.0.0:\n",
                  ).toString("base64"),
                },
              });
            }
            return Promise.reject(new Error("File not found"));
          }),
      } as unknown as OctokitClient;

      const result = await findLockfileVersion(
        mockOctokit,
        "owner",
        "repo",
        "head123",
        "azapal-mobile/package.json",
        "@react-native-community/cli",
      );

      expect(result.resolvedVersion).toBe("18.0.0");
      expect(result.sourceLockfile).toContain("All lockfiles");
      expect(result.sourceLockfile).toContain("package-lock.json");
      expect(result.sourceLockfile).toContain("yarn.lock");
      expect(result.sourceLockfile).toContain("pnpm-lock.yaml");
      expect(result.conflictWarning).toBeUndefined();
    });

    it("compares ALL lockfiles when they disagree and highlights every tool", async () => {
      const mockOctokit = {
        request: jest
          .fn()
          .mockImplementation((endpoint: string, params: any) => {
            if (params.path === "azapal-mobile/package-lock.json") {
              return Promise.resolve({
                data: {
                  type: "file",
                  content: Buffer.from(
                    JSON.stringify({
                      packages: {
                        "node_modules/@react-native-community/cli": {
                          version: "18.0.0",
                        },
                      },
                    }),
                  ).toString("base64"),
                },
              });
            }
            if (params.path === "azapal-mobile/yarn.lock") {
              return Promise.resolve({
                data: {
                  type: "file",
                  content: Buffer.from(
                    '"@react-native-community/cli@latest":\n  version "17.2.0"\n',
                  ).toString("base64"),
                },
              });
            }
            if (params.path === "azapal-mobile/pnpm-lock.yaml") {
              return Promise.resolve({
                data: {
                  type: "file",
                  content: Buffer.from(
                    "packages:\n  /@react-native-community/cli@16.5.0:\n",
                  ).toString("base64"),
                },
              });
            }
            if (params.path === "azapal-mobile/package.json") {
              return Promise.resolve({
                data: {
                  type: "file",
                  content: Buffer.from(
                    JSON.stringify({ packageManager: "pnpm@8.15.0" }),
                  ).toString("base64"),
                },
              });
            }
            return Promise.reject(new Error("File not found"));
          }),
      } as unknown as OctokitClient;

      const result = await findLockfileVersion(
        mockOctokit,
        "owner",
        "repo",
        "head123",
        "azapal-mobile/package.json",
        "@react-native-community/cli",
      );

      // Selected pnpm because packageManager: pnpm@8.15.0
      expect(result.resolvedVersion).toBe("16.5.0");
      expect(result.sourceLockfile).toBe("pnpm-lock.yaml");
      expect(result.conflictWarning).toContain(
        "Lockfile Conflict Detected Across Multiple Tools",
      );
      expect(result.conflictWarning).toContain("package-lock.json");
      expect(result.conflictWarning).toContain("18.0.0");
      expect(result.conflictWarning).toContain("yarn.lock");
      expect(result.conflictWarning).toContain("17.2.0");
      expect(result.conflictWarning).toContain("pnpm-lock.yaml");
      expect(result.conflictWarning).toContain("16.5.0");
      expect(result.conflictWarning).toContain(
        "*(selected — active package manager)*",
      );
    });
  });

  describe("generateSuggestionForFinding", () => {
    it("generates a clean suggestion block preserving indentation and comma", async () => {
      const mockOctokit = {
        request: jest
          .fn()
          .mockImplementation((endpoint: string, params: any) => {
            if (params.path === "azapal-mobile/yarn.lock") {
              return Promise.resolve({
                data: {
                  type: "file",
                  content: Buffer.from(
                    '"@react-native-community/cli@latest":\n  version "18.0.0"\n',
                  ).toString("base64"),
                },
              });
            }
            return Promise.reject(new Error("Not found"));
          }),
      } as unknown as OctokitClient;

      const finding: Finding = {
        rule: "dependency-wildcard-version",
        severity: "medium",
        message: "Wildcard version",
        file: "azapal-mobile/package.json",
        line: 112,
      };

      const lineContent = '    "@react-native-community/cli": "latest",';
      const suggestion = await generateSuggestionForFinding(
        finding,
        lineContent,
        {
          octokit: mockOctokit,
          owner: "owner",
          repo: "repo",
          ref: "main",
        },
      );

      expect(suggestion.suggestionCode).toBe(
        '    "@react-native-community/cli": "^18.0.0",',
      );
      expect(suggestion.sourceNote).toContain("yarn.lock");
    });

    it("generates suggestion for git:// protocol replacement", async () => {
      const finding: Finding = {
        rule: "dependency-insecure-git-protocol",
        severity: "medium",
        message: "git:// protocol",
        file: "package.json",
        line: 15,
      };

      const lineContent = '    "my-lib": "git://github.com/org/repo.git",';
      const suggestion = await generateSuggestionForFinding(
        finding,
        lineContent,
      );

      expect(suggestion.suggestionCode).toBe(
        '    "my-lib": "https://github.com/org/repo.git",',
      );
    });

    it("generates suggestion for docker-run-as-root", async () => {
      const finding: Finding = {
        rule: "docker-run-as-root",
        severity: "high",
        message: "Run as root",
        file: "Dockerfile",
        line: 4,
      };

      const lineContent = "USER root";
      const suggestion = await generateSuggestionForFinding(
        finding,
        lineContent,
      );

      expect(suggestion.suggestionCode).toBe("USER appuser");
    });

    it("generates suggestion for docker-latest-tag", async () => {
      const finding: Finding = {
        rule: "docker-latest-tag",
        severity: "medium",
        message: "Latest tag",
        file: "Dockerfile",
        line: 1,
      };

      const lineContent = "FROM node:latest";
      const suggestion = await generateSuggestionForFinding(
        finding,
        lineContent,
      );

      expect(suggestion.suggestionCode).toBe("FROM node:stable");
    });
  });
});
