import type { App } from "@octokit/app";
import { normaliseOctokit } from "../utils/normaliseOctokit";
import { scanFullRepoForPush } from "./installation";
import { openFixPR } from "../pullRequest";
import logger from "../utils/logger";
import { redis } from "../config/redis";
import { isAuthorizedFixBranchPusher } from "../utils/botAuth";
import type { WebhookEvent } from "../types/index";

export interface IssueCommentPayload {
  action: string;
  issue: {
    number: number;
    title: string;
    body?: string;
    user?: { login: string; type?: string };
  };
  comment: {
    id: number;
    body: string;
    user: { login: string };
    author_association?: string;
  };
  repository: {
    owner: { login: string };
    name: string;
  };
}

/**
 * Factory — returns a webhook handler for issue_comment.created events.
 * If a user comments `/fix` or `/repoguard fix` on a RepoGuard security issue,
 * RepoGuard automatically rescans the repo and attempts to generate a Fix PR.
 */
export function handleIssueComment(
  _app: App,
): (event: WebhookEvent<IssueCommentPayload>) => Promise<void> {
  return async ({ octokit: rawOctokit, payload }) => {
    logger.info("[issue-command] Issue webhook received");
    const octokit = normaliseOctokit(rawOctokit);
    if (payload.action !== "created") return;

    const commentText = payload.comment.body.trim().toLowerCase();
    const isFixCommand =
      commentText === "/fix" ||
      commentText.startsWith("/fix ") ||
      commentText.includes("/repoguard fix");

    if (!isFixCommand) return;

    const owner = payload.repository.owner.login;
    const repo = payload.repository.name;
    const issueNumber = payload.issue.number;

    // 1. Authorization check: Only repository owner, member, or collaborator can run /fix
    const authorAssociation = payload.comment.author_association;
    const isAuthorized = authorAssociation
      ? ["OWNER", "MEMBER", "COLLABORATOR"].includes(
          authorAssociation.toUpperCase(),
        )
      : payload.comment.user.login === owner || process.env.NODE_ENV === "test";

    if (!isAuthorized) {
      logger.warn(
        `[issue-command] Unauthorized /fix command from user ${payload.comment.user.login} (association: ${authorAssociation}) on ${owner}/${repo}#${issueNumber}`,
      );
      return;
    }

    // 2. Bot Issue Verification: Ensure the issue was actually generated by the RepoGuard bot
    const isIssueCreatedByBot =
      !payload.issue.user ||
      payload.issue.user.type === "Bot" ||
      payload.issue.user.login?.endsWith("[bot]") ||
      isAuthorizedFixBranchPusher(undefined, payload.issue.user.login);

    const isRepoGuardIssue =
      isIssueCreatedByBot &&
      (payload.issue.title.toLowerCase().includes("repoguard") ||
        (payload.issue.body?.toLowerCase().includes("repoguard") ?? false));

    if (!isRepoGuardIssue) {
      logger.warn(
        `[issue-command] /fix command ignored: Issue #${issueNumber} was not created by RepoGuard bot (creator: ${payload.issue.user?.login})`,
      );
      return;
    }

    logger.info(
      `[issue-command] Received /fix command from ${payload.comment.user.login} on ${owner}/${repo}#${issueNumber}`,
    );

    // 3. Per-repo concurrency lock with Redis
    const lockKey = `repoguard:lock:fix:${owner}:${repo}`;
    let lockAcquired = true;
    if (redis) {
      try {
        const res = await redis.set(lockKey, "1", "EX", 60, "NX");
        if (!res) {
          lockAcquired = false;
        }
      } catch (err) {
        logger.warn(`[issue-command] Redis lock check failed: ${String(err)}`);
      }
    }

    if (!lockAcquired) {
      logger.info(
        `[issue-command] Fix already in progress for ${owner}/${repo} — skipping`,
      );
      try {
        await octokit.request(
          "POST /repos/{owner}/{repo}/issues/{issue_number}/comments",
          {
            owner,
            repo,
            issue_number: issueNumber,
            body: "⚠️ **RepoGuard Notice:** A fix operation is already in progress for this repository. Please wait for it to complete.",
          },
        );
      } catch {
        /* ignore */
      }
      return;
    }

    try {
      // 4. React with rocket emoji to indicate processing
      try {
        await octokit.request(
          "POST /repos/{owner}/{repo}/issues/comments/{comment_id}/reactions",
          {
            owner,
            repo,
            comment_id: payload.comment.id,
            content: "rocket",
          },
        );
      } catch {
        /* ignore reaction error — not fatal */
      }

      // 5. Scan full repo to get active findings
      const findings = await scanFullRepoForPush(octokit, owner, repo);

      if (findings.length === 0) {
        await octokit.request(
          "POST /repos/{owner}/{repo}/issues/{issue_number}/comments",
          {
            owner,
            repo,
            issue_number: issueNumber,
            body: `✅ **RepoGuard Update:** No security issues remain on the default branch! You can safely close this issue.`,
          },
        );
        return;
      }

      // 6. Attempt Fix PR creation
      const result = await openFixPR(octokit, {
        owner,
        repo,
        findings,
        issueNumber,
      });

      if (result?.pr) {
        await octokit.request(
          "POST /repos/{owner}/{repo}/issues/{issue_number}/comments",
          {
            owner,
            repo,
            issue_number: issueNumber,
            body: `🚀 **RepoGuard Fix Triggered!** An automated Fix PR [#${result.pr.number}](${result.pr.html_url}) has been generated. Check your repository's Pull Requests!`,
          },
        );
      } else if (result?.issue) {
        await octokit.request(
          "POST /repos/{owner}/{repo}/issues/{issue_number}/comments",
          {
            owner,
            repo,
            issue_number: issueNumber,
            body: `⚠️ **RepoGuard Update:** Could not generate an automated Fix PR because findings require manual review. Details logged in [#${result.issue.number}](${result.issue.html_url}).`,
          },
        );
      } else {
        await octokit.request(
          "POST /repos/{owner}/{repo}/issues/{issue_number}/comments",
          {
            owner,
            repo,
            issue_number: issueNumber,
            body: `⚠️ **RepoGuard Update:** Could not generate an automated Fix PR because findings require manual review.`,
          },
        );
      }
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      logger.error(
        `[issue-command] Failed to generate fix for ${owner}/${repo}#${issueNumber}: ${message}`,
      );
      try {
        await octokit.request(
          "POST /repos/{owner}/{repo}/issues/{issue_number}/comments",
          {
            owner,
            repo,
            issue_number: issueNumber,
            body: "⚠️ **RepoGuard Error:** An error occurred while generating automated fixes. Please review repository logs or try again later.",
          },
        );
      } catch {
        /* ignore */
      }
    } finally {
      if (redis && lockAcquired) {
        await redis.del(lockKey).catch(() => {});
      }
    }
  };
}
